-- Initial schema for the payment application.
--
-- IF NOT EXISTS clauses make this migration safe for databases that were
-- originally created by Hibernate's ddl-auto=update before Flyway was
-- introduced. Fresh databases get the complete schema from this file.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP,
    qr_receive VARCHAR(255),
    qr_pay VARCHAR(255),
    business BOOLEAN NOT NULL DEFAULT FALSE,
    balance NUMERIC(19, 4) NOT NULL DEFAULT 0,
    token_version BIGINT NOT NULL DEFAULT 0,
    payment_code_hash VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_users_balance_non_negative CHECK (balance >= 0)
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS balance NUMERIC(19, 4) NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS payment_code_hash VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS ux_users_nickname ON users (nickname);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email ON users (email);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_qr_receive ON users (qr_receive);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_qr_pay ON users (qr_pay);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    amount NUMERIC(19, 4) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    transaction_status VARCHAR(255) NOT NULL,
    transaction_time TIMESTAMP,
    transaction_type VARCHAR(255) NOT NULL,
    method VARCHAR(255) NOT NULL,
    CONSTRAINT ck_transactions_amount_positive CHECK (amount > 0)
);

CREATE INDEX IF NOT EXISTS ix_transactions_sender ON transactions (sender_id, transaction_time);
CREATE INDEX IF NOT EXISTS ix_transactions_receiver ON transactions (receiver_id, transaction_time);

CREATE TABLE IF NOT EXISTS payment_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL,
    payer_id BIGINT NOT NULL,
    amount NUMERIC(19, 4) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(255) NOT NULL,
    note VARCHAR(255),
    created_at TIMESTAMP,
    resolved_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_payment_requests_amount_positive CHECK (amount > 0)
);

ALTER TABLE payment_requests ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS ix_payment_requests_payer_status
    ON payment_requests (payer_id, status, created_at);
CREATE INDEX IF NOT EXISTS ix_payment_requests_requester_status
    ON payment_requests (requester_id, status, created_at);

CREATE TABLE IF NOT EXISTS contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    contact_id BIGINT NOT NULL,
    created_at TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_contacts_owner_contact_idx ON contacts (owner_id, contact_id);
CREATE INDEX IF NOT EXISTS ix_contacts_owner ON contacts (owner_id, created_at);
